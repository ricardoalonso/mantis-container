#!/bin/bash
# Writes config_inc.php from MANTIS_* environment variables -- once.
#
#  - config_inc.php already exists in the config folder: nothing is touched.
#    The file on the volume is the source of truth from then on; edit it, or
#    delete it and restart to regenerate it from the environment.
#  - MANTIS_DB_HOST is not set: nothing is generated, and the web installer
#    (admin/install.php) is the way in, as before.
#
# Secrets can come from files: MANTIS_DB_PASSWORD_FILE=/run/secrets/db, etc.
set -euo pipefail

# shellcheck source=../lib/mantis/common.sh
source /usr/local/lib/mantis/common.sh
set_defaults

CONFIG_FILE="${MANTIS_CONFIG_FOLDER%/}/config_inc.php"

for v in MANTIS_DB_HOST MANTIS_DB_USER MANTIS_DB_PASSWORD MANTIS_CRYPTO_MASTER_SALT \
         MANTIS_SMTP_USERNAME MANTIS_SMTP_PASSWORD \
         MANTIS_LDAP_BIND_DN MANTIS_LDAP_BIND_PASSWORD; do
	file_env "$v"
done

if [ -e "$CONFIG_FILE" ]; then
	log "Using existing $CONFIG_FILE (MANTIS_DB_* and similar variables are ignored)"
	# OpenID Connect is configured on every start, but only takes effect if
	# config_inc.php loads the file it is written to. Files generated before
	# OpenID Connect support, and hand-written ones, do not.
	if [ -n "$MANTIS_OIDC_ISSUER" ] && ! grep -qF "$MANTIS_RUNTIME_INC" "$CONFIG_FILE"; then
		die "MANTIS_OIDC_ISSUER is set, but $CONFIG_FILE does not load $MANTIS_RUNTIME_INC, so MantisBT would ignore it. Add this at the end of it:
	if( file_exists( '$MANTIS_RUNTIME_INC' ) ) {
		require '$MANTIS_RUNTIME_INC';
	}"
	fi
	exit 0
fi

if [ -z "${MANTIS_DB_HOST:-}" ]; then
	if is_true MANTIS_ADMINISTRATION_ENABLED; then
		log "No $CONFIG_FILE and no MANTIS_DB_HOST: open $(context_path)/admin/install.php to install"
	else
		warn "No $CONFIG_FILE, no MANTIS_DB_HOST, and the admin pages are disabled."
		warn "Either set the MANTIS_DB_* variables, or set MANTIS_ADMINISTRATION_ENABLED=true and use $(context_path)/admin/install.php"
	fi
	exit 0
fi

# --- Validation --------------------------------------------------------------
require_match MANTIS_DB_TYPE '^(mysqli|pgsql)$' "mysqli or pgsql (the drivers in this image)"
require_match MANTIS_FILE_UPLOAD_METHOD '^(DISK|DATABASE)$' "DISK or DATABASE"
[ -n "${MANTIS_DB_USER:-}" ] || die "MANTIS_DB_HOST is set, so MANTIS_DB_USER is required"
for v in $(compgen -e | grep '^MANTIS_'); do
	require_one_line "$v"
done
[ -z "${MANTIS_FILE_UPLOAD_SUBDIRECTORY_DEPTH:-}" ] || require_int MANTIS_FILE_UPLOAD_SUBDIRECTORY_DEPTH 0
[ -z "${MANTIS_FILE_UPLOAD_SUBDIRECTORY_WIDTH:-}" ] || require_int MANTIS_FILE_UPLOAD_SUBDIRECTORY_WIDTH 1
if [ -n "${MANTIS_SMTP_HOST:-}" ]; then
	require_int MANTIS_SMTP_PORT 1
	require_match MANTIS_SMTP_CONNECTION_MODE '^(tls|ssl|none)$' "tls (STARTTLS), ssl (implicit TLS) or none"
fi
if [ -n "${MANTIS_LDAP_SERVER:-}" ]; then
	require_int MANTIS_LDAP_PROTOCOL_VERSION 2
	require_bool MANTIS_LDAP_USE_STARTTLS
	require_bool MANTIS_LDAP_FOLLOW_REFERRALS
	require_bool MANTIS_LDAP_USE_EMAIL
	require_bool MANTIS_LDAP_USE_REALNAME
fi

if [ -n "${MANTIS_PATH:-}" ]; then
	require_match MANTIS_PATH '^https?://' "a full URL such as https://bugs.example.com/"
	MANTIS_PATH="${MANTIS_PATH%/}/"
fi
MANTIS_UPLOAD_FOLDER="${MANTIS_UPLOAD_FOLDER%/}/"

if [ -z "${MANTIS_CRYPTO_MASTER_SALT:-}" ]; then
	# Stored in the generated file on the volume, so it survives restarts and
	# image upgrades. Changing it later invalidates existing sessions/tokens.
	MANTIS_CRYPTO_MASTER_SALT=$(openssl rand -base64 48 | tr -d '\n')
	log "Generated a crypto_master_salt (kept in $CONFIG_FILE)"
fi
(( ${#MANTIS_CRYPTO_MASTER_SALT} >= 16 )) || die "MANTIS_CRYPTO_MASTER_SALT must be at least 16 characters"

[ -w "$MANTIS_CONFIG_FOLDER" ] \
	|| die "$MANTIS_CONFIG_FOLDER is not writable by uid $(id -u). For a bind mount, run: podman unshare chown 48:0 <dir>"

# --- Generation --------------------------------------------------------------

# php_bool <NAME>
php_bool() { is_true "$1" && echo ON || echo OFF; }

tmp=$(mktemp "${MANTIS_CONFIG_FOLDER%/}/.config_inc.XXXXXX")
trap 'rm -f "$tmp"' EXIT
chmod 0640 "$tmp"

{
cat <<EOF
<?php
# Generated by the container on $(date -u +%Y-%m-%dT%H:%M:%SZ) from MANTIS_* variables.
#
# Generated once: from now on this file is used as is and the variables are
# ignored. Edit it freely, or delete it and restart the container to generate
# it again. Every option is described in config_defaults_inc.php.

# --- Database ---
\$g_hostname      = $(php_str "$MANTIS_DB_HOST");
\$g_db_type       = $(php_str "$MANTIS_DB_TYPE");
\$g_database_name = $(php_str "$MANTIS_DB_NAME");
\$g_db_username   = $(php_str "$MANTIS_DB_USER");
\$g_db_password   = $(php_str "${MANTIS_DB_PASSWORD:-}");

# --- Security ---
\$g_crypto_master_salt = $(php_str "$MANTIS_CRYPTO_MASTER_SALT");
EOF

if [ -n "${MANTIS_PATH:-}" ]; then
cat <<EOF

# --- URL ---
\$g_path = $(php_str "$MANTIS_PATH");
EOF
fi

cat <<EOF

# --- Attachments ---
\$g_file_upload_method = $MANTIS_FILE_UPLOAD_METHOD;
\$g_absolute_path_default_upload_folder = $(php_str "$MANTIS_UPLOAD_FOLDER");
# The PHP limits (PHP_UPLOAD_MAX_FILESIZE / PHP_POST_MAX_SIZE) decide the
# maximum upload size; MantisBT uses the smallest of the three.
\$g_max_file_size = PHP_INT_MAX;
EOF
[ -n "${MANTIS_FILE_UPLOAD_SUBDIRECTORY_DEPTH:-}" ] \
	&& echo "\$g_file_upload_subdirectory_depth = $MANTIS_FILE_UPLOAD_SUBDIRECTORY_DEPTH;"
[ -n "${MANTIS_FILE_UPLOAD_SUBDIRECTORY_WIDTH:-}" ] \
	&& echo "\$g_file_upload_subdirectory_width = $MANTIS_FILE_UPLOAD_SUBDIRECTORY_WIDTH;"

echo
echo "# --- Email ---"
if [ -n "${MANTIS_SMTP_HOST:-}" ]; then
	mode=$MANTIS_SMTP_CONNECTION_MODE; [ "$mode" = none ] && mode=''
cat <<EOF
\$g_phpMailer_method     = PHPMAILER_METHOD_SMTP;
\$g_smtp_host            = $(php_str "$MANTIS_SMTP_HOST");
\$g_smtp_port            = $MANTIS_SMTP_PORT;
\$g_smtp_connection_mode = $(php_str "$mode");
\$g_smtp_username        = $(php_str "${MANTIS_SMTP_USERNAME:-}");
\$g_smtp_password        = $(php_str "${MANTIS_SMTP_PASSWORD:-}");
EOF
else
	echo "# No MANTIS_SMTP_HOST: there is no local mail server in the container,"
	echo "# so notifications are off rather than failing on every action."
	echo "\$g_enable_email_notification = OFF;"
fi
[ -n "${MANTIS_EMAIL_FROM:-}" ]        && echo "\$g_from_email        = $(php_str "$MANTIS_EMAIL_FROM");"
[ -n "${MANTIS_EMAIL_FROM_NAME:-}" ]   && echo "\$g_from_name         = $(php_str "$MANTIS_EMAIL_FROM_NAME");"
[ -n "${MANTIS_EMAIL_WEBMASTER:-}" ]   && echo "\$g_webmaster_email   = $(php_str "$MANTIS_EMAIL_WEBMASTER");"
[ -n "${MANTIS_EMAIL_RETURN_PATH:-}" ] && echo "\$g_return_path_email = $(php_str "$MANTIS_EMAIL_RETURN_PATH");"

if [ -n "${MANTIS_LDAP_SERVER:-}" ]; then
cat <<EOF

# --- LDAP ---
\$g_login_method          = LDAP;
\$g_ldap_server           = $(php_str "$MANTIS_LDAP_SERVER");
\$g_ldap_root_dn          = $(php_str "${MANTIS_LDAP_ROOT_DN:-}");
\$g_ldap_organization     = $(php_str "${MANTIS_LDAP_ORGANIZATION:-}");
\$g_ldap_bind_dn          = $(php_str "${MANTIS_LDAP_BIND_DN:-}");
\$g_ldap_bind_passwd      = $(php_str "${MANTIS_LDAP_BIND_PASSWORD:-}");
\$g_ldap_uid_field        = $(php_str "$MANTIS_LDAP_UID_FIELD");
\$g_ldap_protocol_version = $MANTIS_LDAP_PROTOCOL_VERSION;
\$g_ldap_use_starttls     = $(php_bool MANTIS_LDAP_USE_STARTTLS);
\$g_ldap_follow_referrals = $(php_bool MANTIS_LDAP_FOLLOW_REFERRALS);
\$g_use_ldap_email        = $(php_bool MANTIS_LDAP_USE_EMAIL);
\$g_use_ldap_realname     = $(php_bool MANTIS_LDAP_USE_REALNAME);
EOF
fi

cat <<'EOF'

# --- Local additions ---
# Any *.php file in config_inc.d/ next to this file is loaded last, in name
# order, so site-specific settings can live outside the generated file.
foreach( glob( __DIR__ . '/config_inc.d/*.php' ) ?: array() as $t_config_file ) {
	require $t_config_file;
}
unset( $t_config_file );
EOF

cat <<EOF

# --- Container runtime settings ---
# Written by the container on every start from the MANTIS_OIDC_* variables,
# and loaded last, so those variables win over anything above.
if( file_exists( $(php_str "$MANTIS_RUNTIME_INC") ) ) {
	require $(php_str "$MANTIS_RUNTIME_INC");
}
EOF
} > "$tmp"

php -l "$tmp" >/dev/null || die "generated config_inc.php has a syntax error; this is a bug in mantis-config.sh"
mv "$tmp" "$CONFIG_FILE"
trap - EXIT
log "Wrote $CONFIG_FILE"
